/**
 * Retorna o SVG de um ícone como string (use dentro do html``).
 * @param {keyof I} nome
 * @param {{ tamanho?: number, classe?: string, rotulo?: string }} [opcoes]
 */
export function icone(nome, { tamanho = 18, classe = '', rotulo = '' } = {}) {
  const corpo = I[nome];
  if (!corpo) return raw('');
  const a11y = rotulo ? `role="img" aria-label="${rotulo}"` : 'aria-hidden="true" focusable="false"';
  return raw(`<svg class="ico ${classe}" width="${tamanho}" height="${tamanho}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${corpo}</svg>`);
}

/** Ícones de status desenhados para o Pauta (o desenho comunica o estado, não só a cor). */
export function iconeStatus(status, tamanho = 16) {
  const base = `class="ico ico-status s${status}" width="${tamanho}" height="${tamanho}" viewBox="0 0 16 16" aria-hidden="true" focusable="false"`;
  switch (Number(status)) {
    case 1: // A fazer: círculo tracejado
      return raw(`<svg ${base}><circle cx="8" cy="8" r="6" fill="none" stroke="currentColor" stroke-width="1.6" stroke-dasharray="2.4 2.1"/></svg>`);
    case 2: // Em andamento: meio preenchido
      return raw(`<svg ${base}><circle cx="8" cy="8" r="6" fill="none" stroke="currentColor" stroke-width="1.6"/><path d="M8 4.2a3.8 3.8 0 0 1 0 7.6z" fill="currentColor"/></svg>`);
    case 3: // Concluída: cheio com check
      return raw(`<svg ${base}><circle cx="8" cy="8" r="6.8" fill="currentColor"/><path d="M5.2 8.2l1.9 1.9 3.8-4" fill="none" stroke="var(--on-status, #fff)" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round"/></svg>`);
    default: // Cancelada: círculo cortado
      return raw(`<svg ${base}><circle cx="8" cy="8" r="6" fill="none" stroke="currentColor" stroke-width="1.6"/><path d="M4.6 11.4l6.8-6.8" stroke="currentColor" stroke-width="1.6" stroke-linecap="round"/></svg>`);
  }
}

/** Prioridade: barras de sinal (1–3) e um selo de exclamação para Urgente. */
export function iconePrioridade(prioridade, tamanho = 16) {
  const p = Number(prioridade);
  const base = `class="ico ico-prio p${p}" width="${tamanho}" height="${tamanho}" viewBox="0 0 16 16" aria-hidden="true" focusable="false"`;
  if (p === 4) {
    return raw(`<svg ${base}><rect x="1.5" y="1.5" width="13" height="13" rx="3.5" fill="currentColor"/><path d="M8 4.6v4.2" stroke="var(--on-status, #fff)" stroke-width="1.8" stroke-linecap="round"/><circle cx="8" cy="11.3" r="1.05" fill="var(--on-status, #fff)"/></svg>`);
  }
  const barras = [
    { x: 2, h: 5 },
    { x: 6.5, h: 8.5 },
    { x: 11, h: 12 },
  ];
  return raw(`<svg ${base}>${barras
    .map((b, i) => `<rect x="${b.x}" y="${14 - b.h}" width="3" height="${b.h}" rx="1" fill="currentColor" opacity="${i < p ? 1 : 0.22}"/>`)
    .join('')}</svg>`);
}

